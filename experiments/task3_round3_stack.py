"""Train-only selection, independent local evaluation, then all-meta-data refit.

Requires the positive-only component caches generated by task3_round2.py.
Neither test labels nor leaderboard feedback tune hyperparameters or weights.
"""
import os
os.environ['OPENBLAS_NUM_THREADS']='1'
os.environ['OMP_NUM_THREADS']='1'
import argparse,hashlib,json,itertools
from pathlib import Path
import numpy as np
import pandas as pd
from catboost import CatBoostRegressor
from task3_round3 import extended_design,user_ridge,ordinal_ridge,clip,mse,dataset

def configuration(depth,seed=42):
    return dict(iterations=2200,depth=depth,learning_rate=.025,l2_leaf_reg=20,random_seed=seed,thread_count=2,loss_function='RMSE',allow_writing_files=False,verbose=False)

def main():
    ap=argparse.ArgumentParser()
    for key in ['data-dir','legacy','prior','round2','out']:ap.add_argument('--'+key,type=Path,required=True)
    ap.add_argument('--predict',action='store_true');args=ap.parse_args();args.out.mkdir(parents=True,exist_ok=True)
    manifest={f:hashlib.sha256((args.data_dir/f).read_bytes()).hexdigest() for f in ['tasks_3_4_train.csv','task_3_test.csv']}
    assert json.loads((args.round2/'manifest.json').read_text())==manifest
    user_ridge(args.data_dir,args.prior,args.out/'validation');ordinal_ridge(args.data_dir,args.prior,args.round2,args.out/'validation')
    X,anchor,names=extended_design(args.data_dir,args.legacy,args.prior,args.round2,args.out)
    guard=args.out/'stack_manifest.json';expected={'input_manifest':manifest,'features':names,'inner_seed':17,'config':configuration(6),'rows':len(X),'anchor':'mean(learned_rating25_365,wide_learned_rating25_365)'}
    if guard.exists():assert json.loads(guard.read_text())==expected, 'Changed inputs/config: use a fresh output directory'
    guard.write_text(json.dumps(expected,indent=2))
    p,tr,q,*_=dataset(args.data_dir,False);y=q.rating.to_numpy();n=int(.95*len(p))-int(.9*len(p));idx=np.random.RandomState(17).permutation(n);a=idx[:int(.8*n)];b=idx[int(.8*n):];report=[];inner={}
    for residual,depth in [(True,6),(False,6),(False,8)]:
        name=f'cat_{depth}_res{int(residual)}';path=args.out/(name+'_inner.cbm');cfg=configuration(depth);target=y-anchor if residual else y
        if path.exists():m=CatBoostRegressor();m.load_model(str(path))
        else:
            m=CatBoostRegressor(**cfg);m.fit(X[a],target[a],eval_set=(X[b],target[b]),early_stopping_rounds=150);m.save_model(str(path))
        pred=clip(m.predict(X[b])+(anchor[b] if residual else 0));iterations=m.tree_count_;r=dict(name=name,kind='catboost',extended=True,residual=residual,config=cfg,iterations=iterations,inner_MSE=mse(y[b],pred));report.append(r);inner[name]=pred
        print(json.dumps(r),flush=True)
    # Select singles or pairs inside selection only. Penalize deploying a second
    # learner by .0002 MSE so tiny mixture gains do not add a whole extra model.
    candidates=[(r['inner_MSE'],r['inner_MSE'],{r['name']:1.}) for r in report]
    for left,right in itertools.combinations(report,2):
        for w in [.25,.5,.75]:
            score=mse(y[b],w*inner[left['name']]+(1-w)*inner[right['name']]);candidates.append((score+.0002,score,{left['name']:w,right['name']:1-w}))
    penalized,score,weights=min(candidates,key=lambda r:r[0]);chosen=[r for r in report if r['name'] in weights];evals={}
    for r in chosen:
        target=y-anchor if r['residual'] else y;cfg={**r['config'],'iterations':r['iterations']};m=CatBoostRegressor(**cfg);m.fit(X[:n],target[:n]);m.save_model(str(args.out/(r['name']+'_evaluation.cbm')));evals[r['name']]=clip(m.predict(X[n:])+(anchor[n:] if r['residual'] else 0))
    pred=sum(weights[k]*v for k,v in evals.items())
    old=[np.load(args.round2/'models'/k/'evaluation.npz') for k in ['plain','common']];assert all(np.array_equal(z['y'],y[n:]) for z in old);reference=.5*(old[0]['selected']+old[1]['selected'])
    summary=dict(search=report,selected=dict(weights=weights,inner_MSE=score,penalized_inner_MSE=penalized,second_model_penalty=.0002),evaluation_MSE=mse(y[n:],pred),reference_evaluation_MSE=mse(y[n:],reference),conservative_evaluation_MSE=mse(y[n:],.5*pred+.5*reference),component_evaluation_MSE={k:mse(y[n:],v) for k,v in evals.items()},input_manifest=manifest,features=names,meta_selection_rows=n,final_meta_training_rows=len(y),reported_reference_public_MSE=.6855387514011825)
    np.savez_compressed(args.out/'evaluation.npz',y=y[n:],new=pred,reference=reference,**evals);(args.out/'results.json').write_text(json.dumps(summary,indent=2));print('LOCAL',summary['evaluation_MSE'],'reference',summary['reference_evaluation_MSE'],flush=True)
    if not args.predict:return
    user_ridge(args.data_dir,args.prior,args.out/'full',True);ordinal_ridge(args.data_dir,args.prior,args.round2,args.out/'full',True)
    FX,fa,fn=extended_design(args.data_dir,args.legacy,args.prior,args.round2,args.out,True);assert names==fn;preds={}
    for r in chosen:
        target=y-anchor if r['residual'] else y;cfg={**r['config'],'iterations':r['iterations']};m=CatBoostRegressor(**cfg);m.fit(X,target);m.save_model(str(args.out/(r['name']+'_full.cbm')));preds[r['name']]=clip(m.predict(FX)+(fa if r['residual'] else 0))
    primary=clip(sum(weights[k]*v for k,v in preds.items()));old=np.load(args.round2/'test_predictions.npz')['blend'];conservative=clip(.5*primary+.5*old);test=pd.read_csv(args.data_dir/'task_3_test.csv');assert len(test)==20000;assert np.isfinite(primary).all()
    for label,v in [('primary',primary),('conservative',conservative)]:
        folder=args.out/label;folder.mkdir(exist_ok=True);frame=test.copy();frame['rating']=v;frame.to_csv(folder/'task_3_predictions.csv',index=False)
    np.savez_compressed(args.out/'test_predictions.npz',primary=primary,conservative=conservative,reference=old,**preds)
if __name__=='__main__':main()
